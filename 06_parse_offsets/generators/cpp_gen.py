"""C++ Header Generator (offsets.h)."""

from datetime import datetime


def generate_cpp(data: dict, namespace_name: str = "Offsets") -> str:
    profile_name = data.get("profile", "generic")
    methods = data.get("methods", {})
    fields = data.get("fields", {})
    typeinfos = data.get("typeinfos", {})
    native = data.get("native", {})

    lines = [
        "// ===========================================================================",
        f"// Generated by GSS4 Offset Pipeline - Profile: {profile_name}",
        f"// Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "// ===========================================================================",
        "#pragma once",
        "#include <cstdint>",
        "",
        f"namespace {namespace_name} {{",
        "",
        "    // ========================================================================",
        "    // METHOD RVAs (libil2cpp.so)",
        "    // ========================================================================"
    ]

    for sym, rva in methods.items():
        lines.append(f"    constexpr uintptr_t {sym} = 0x{rva:X};")

    lines.append("")
    lines.append("    // ========================================================================")
    lines.append("    // CLASS FIELD OFFSETS")
    lines.append("    // ========================================================================")

    for cname, cfields in fields.items():
        if not cfields:
            continue
        lines.append(f"    namespace {cname} {{")
        for fname, foff in cfields.items():
            lines.append(f"        constexpr uintptr_t {fname} = 0x{foff:X};")
        lines.append("    }")

    lines.append("")
    lines.append("    // ========================================================================")
    lines.append("    // TYPEINFO POINTERS (libil2cpp.so file offsets)")
    lines.append("    // ========================================================================")
    lines.append("    namespace TypeInfo {")
    for tname, foff in typeinfos.items():
        lines.append(f"        constexpr uintptr_t {tname} = 0x{foff:X};")
    lines.append("    }")

    if native:
        lines.append("")
        lines.append("    // ========================================================================")
        lines.append("    // NATIVE OFFSETS (libunity.so / native libraries)")
        lines.append("    // ========================================================================")
        lines.append("    namespace Native {")
        for nname, foff in native.items():
            lines.append(f"        constexpr uintptr_t {nname} = 0x{foff:X};")
        lines.append("    }")

    lines.append(f"}} // namespace {namespace_name}")
    lines.append("")
    return "\n".join(lines)
