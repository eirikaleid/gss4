"""Rust Module Generator (offsets.rs)."""

from datetime import datetime


def generate_rust(data: dict) -> str:
    profile_name = data.get("profile", "generic")
    methods = data.get("methods", {})
    fields = data.get("fields", {})
    typeinfos = data.get("typeinfos", {})
    native = data.get("native", {})

    lines = [
        "// ===========================================================================",
        f"// Generated by GSS4 Offset Pipeline - Profile: {profile_name}",
        f"// Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "// ===========================================================================",
        "#![allow(dead_code, non_upper_case_globals)]",
        "",
        "pub mod methods {"
    ]

    for sym, rva in methods.items():
        lines.append(f"    pub const {sym}: usize = 0x{rva:X};")
    lines.append("}")
    lines.append("")

    lines.append("pub mod fields {")
    for cname, cfields in fields.items():
        if not cfields:
            continue
        lines.append(f"    pub mod {cname} {{")
        for fname, foff in cfields.items():
            lines.append(f"        pub const {fname}: usize = 0x{foff:X};")
        lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("pub mod type_info {")
    for tname, foff in typeinfos.items():
        lines.append(f"    pub const {tname}: usize = 0x{foff:X};")
    lines.append("}")

    if native:
        lines.append("")
        lines.append("pub mod native {")
        for nname, foff in native.items():
            lines.append(f"    pub const {nname}: usize = 0x{foff:X};")
        lines.append("}")

    lines.append("")
    return "\n".join(lines)
