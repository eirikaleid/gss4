"""C# Class Generator (Offsets.cs)."""

from datetime import datetime


def generate_csharp(data: dict) -> str:
    profile_name = data.get("profile", "generic")
    methods = data.get("methods", {})
    fields = data.get("fields", {})
    typeinfos = data.get("typeinfos", {})
    native = data.get("native", {})

    lines = [
        "// ===========================================================================",
        f"// Generated by GSS4 Offset Pipeline - Profile: {profile_name}",
        f"// Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "// ===========================================================================",
        "using System;",
        "",
        "namespace GSS4.Offsets",
        "{",
        "    public static class Methods",
        "    {"
    ]

    for sym, rva in methods.items():
        lines.append(f"        public const ulong {sym} = 0x{rva:X};")
    lines.append("    }")
    lines.append("")

    lines.append("    public static class Fields")
    lines.append("    {")
    for cname, cfields in fields.items():
        if not cfields:
            continue
        lines.append(f"        public static class {cname}")
        lines.append("        {")
        for fname, foff in cfields.items():
            lines.append(f"            public const int {fname} = 0x{foff:X};")
        lines.append("        }")
    lines.append("    }")
    lines.append("")

    lines.append("    public static class TypeInfo")
    lines.append("    {")
    for tname, foff in typeinfos.items():
        lines.append(f"        public const ulong {tname} = 0x{foff:X};")
    lines.append("    }")

    if native:
        lines.append("")
        lines.append("    public static class Native")
        lines.append("    {")
        for nname, foff in native.items():
            lines.append(f"        public const ulong {nname} = 0x{foff:X};")
        lines.append("    }")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)
